/** Reads <html lang> once per call so a client-side nav swap stays correct. */
export function currentLocale() {
  const raw = (document.documentElement.lang || 'pt').toLowerCase();
  if (raw.startsWith('en')) return 'en';
  if (raw.startsWith('es')) return 'es';
  return 'pt';
}

export function t(key, ...args) {
  const table = STRINGS[currentLocale()] || STRINGS.pt;
  const entry = table[key] ?? STRINGS.pt[key];
  if (entry === undefined) return key;
  return typeof entry === 'function' ? entry(...args) : entry;
}
